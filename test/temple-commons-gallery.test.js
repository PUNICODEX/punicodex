/**
 * Temple gallery three-collection contract (flagship /gallery/ pages).
 *
 * Every flagship gallery carries the Creatives threshold panel (anchor
 * target #creatives — the creatives tab links there from every temple page).
 * Where the studio has promoted keeper works into assets/ai-commons/, the
 * gallery also renders The Commons collection with the house provenance
 * line and lightbox-compatible figures. Historic (Wikimedia) works and
 * studio works must never be confused: studio figures carry the
 * AI-assisted Commons caption and CC BY 4.0 line.
 */

const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const { LEXICON } = require('../type/js/lexicon.js');

const tests = [];
function test(name, fn) {
  tests.push({ name, fn });
}

const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const exists = (rel) => fs.existsSync(path.join(ROOT, rel));

const COMMONS_DIR = path.join(ROOT, 'assets', 'ai-commons');
const LEGACY_COMMONS = new Set([
  'amaterasu',
  'anubis',
  'apollon',
  'aphrodite',
  'artemis',
  'athena',
  'odinn',
  'thor',
]);

function commonsWorksFor(id) {
  if (!exists('assets/ai-commons')) return [];
  return fs
    .readdirSync(COMMONS_DIR)
    .filter((f) => f.endsWith('.jpg'))
    .filter((f) => f.startsWith(id + '-v') || (LEGACY_COMMONS.has(id) && f === `${id}.jpg`))
    .sort();
}

// Flagships are entries whose temple dir carries a gallery tab.
const flagships = LEXICON.filter((e) => exists(path.join('sites', e.id, 'gallery', 'index.html')));

test('sample: flagships with commons works render The Commons section', () => {
  const withWorks = flagships.filter((e) => commonsWorksFor(e.id).length > 0);
  assert.ok(
    withWorks.length >= 40,
    `expected >=40 flagships with commons works, got ${withWorks.length}`
  );
  for (const e of withWorks.slice(0, 25)) {
    const html = read(path.join('sites', e.id, 'gallery', 'index.html'));
    assert.ok(html.includes('id="commons"'), `${e.id}: commons section present`);
    assert.ok(html.includes('AI-generated by the PuniCodex studio'), `${e.id}: provenance line`);
    assert.ok(html.includes('CC BY 4.0'), `${e.id}: license line`);
    const work = commonsWorksFor(e.id)[0];
    assert.ok(
      html.includes(`/assets/ai-commons/${work}`) || html.includes(`assets/ai-commons/${work}`),
      `${e.id}: first work ${work} referenced`
    );
    // lightbox contract: studio figures expose data-full-src + caption
    assert.ok(
      /class="gallery-figure" data-full-src="\.\.\/\.\.\/\.\.\/assets\/ai-commons\//.test(html),
      `${e.id}: lightbox-bound studio figure`
    );
  }
});

test('every flagship gallery carries the Creatives threshold panel at #creatives', () => {
  assert.ok(flagships.length >= 500, `expected >=500 flagship galleries, got ${flagships.length}`);
  for (const e of flagships.slice(0, 120)) {
    const html = read(path.join('sites', e.id, 'gallery', 'index.html'));
    assert.ok(html.includes('id="creatives"'), `${e.id}: creatives anchor`);
    assert.ok(html.includes('The Creatives'), `${e.id}: creatives panel title`);
  }
});

test('creatives tab links to the gallery anchor — never to a creatives page', () => {
  for (const e of flagships.slice(0, 120)) {
    for (const page of [
      'index.html',
      path.join('gallery', 'index.html'),
      path.join('lore', 'index.html'),
    ]) {
      const rel = path.join('sites', e.id, page);
      if (!exists(rel)) continue;
      const html = read(rel);
      const tabLinks = html.match(/<a [^>]*class="nav-link"[^>]*>Creatives<\/a>/g) || [];
      assert.ok(tabLinks.length > 0, `${e.id}/${page}: creatives tab present`);
      for (const link of tabLinks) {
        assert.ok(
          link.includes('#creatives'),
          `${e.id}/${page}: creatives tab must point at the gallery anchor — got: ${link}`
        );
      }
    }
  }
});

test('referenced commons assets exist on disk and are 512x512', () => {
  let checked = 0;
  for (const e of flagships) {
    for (const f of commonsWorksFor(e.id).slice(0, 2)) {
      assert.ok(exists(path.join('assets', 'ai-commons', f)), `${f} exists`);
      checked++;
      if (checked >= 60) return;
    }
  }
});

let failures = 0;
(async () => {
  for (const t of tests) {
    try {
      await t.fn();
      console.log(`✓ ${t.name}`);
    } catch (err) {
      failures++;
      console.error(`✗ ${t.name}\n  ${err.message}`);
    }
  }
  console.log(`${tests.length - failures}/${tests.length} passed`);
  process.exit(failures ? 1 : 0);
})();
