/**
 * PUNYCODEX — Generate Cloudflare Pages _redirects for archetype paths
 *
 * Rewrites punycodex.com/{id}/* → /sites/{id}/* for every built flagship,
 * matching the behavior of middleware.js on Vercel.
 */

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const archetypesPath = path.join(root, 'js', 'archetypes-v2.js');
const redirectsPath = path.join(root, '_redirects');

const content = fs.readFileSync(archetypesPath, 'utf8');
const ids = new Set();
const idRegex = /id:\s*"([^"]+)"/g;
let match;
while ((match = idRegex.exec(content)) !== null) {
  const id = match[1];
  const after = content.slice(match.index, match.index + 800);
  if (after.includes('built: true')) {
    ids.add(id);
  }
}

const lines = Array.from(ids).sort().map(id => `/${id}/* /sites/${id}/:splat 200`);

const output = `# PUNYCODEX — Cloudflare Pages path rewrites for flagship temples
# Generated by scripts/generate-redirects.js
# Rewrites clean /{id}/* paths to the underlying /sites/{id}/* directories

${lines.join('\n')}
`;

fs.writeFileSync(redirectsPath, output, 'utf8');
console.log(`Generated ${lines.length} path rewrites in _redirects`);
