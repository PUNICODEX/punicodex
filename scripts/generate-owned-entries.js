/**
 * PuniCodex — Generate owned-entry lookup for the browser
 *
 * Reads platform/db/owned-domains.json and the canonical lexicon, then writes
 * js/owned-entries.js containing a Set of entry ids that own at least one
 * domain. The lexicon browse page uses this to decide which plain-ASCII
 * entries are still worth displaying by default.
 */

const fs = require('node:fs');
const path = require('node:path');
const { domainToUnicode } = require('node:url');

const ROOT = path.join(__dirname, '..');
const OWNED_DOMAINS_PATH = path.join(ROOT, 'platform', 'db', 'owned-domains.json');
const LEXICON_PATH = path.join(ROOT, 'type', 'js', 'lexicon.js');
const OUTPUT_PATH = path.join(ROOT, 'js', 'owned-entries.js');

function normalizeLabel(label) {
  return label.normalize('NFC').toLowerCase().trim();
}

// Domains cannot carry apostrophes/hyphens/spaces, so a display label like
// "Cháng'é" never literally equals its domain label "chángé". Compare a
// punctuation-free form alongside the exact one.
function squashLabel(label) {
  return normalizeLabel(label).replace(/['’\-.\s]/g, '');
}

function stripTldAndWww(domain) {
  let label = domain;
  // Remove trailing TLD
  const lastDot = label.lastIndexOf('.');
  if (lastDot > 0) {
    label = label.slice(0, lastDot);
  }
  if (label.startsWith('www.')) {
    label = label.slice(4);
  }
  return label;
}

function ownedDomainLabels(ownedDomains) {
  const labels = new Set();
  for (const raw of ownedDomains) {
    try {
      const unicodeDomain = domainToUnicode(raw);
      const label = stripTldAndWww(unicodeDomain);
      if (label) {
        labels.add(normalizeLabel(label));
        labels.add(squashLabel(label));
      }
    } catch {
      // Malformed domain; skip
    }
  }
  return labels;
}

function entryLabels(entry) {
  const labels = new Set();
  const add = (value) => {
    if (value) {
      labels.add(normalizeLabel(value));
      labels.add(squashLabel(value));
    }
  };
  for (const key of ['unicode', 'ascii']) add(entry[key]);
  if (Array.isArray(entry.variants)) {
    for (const variant of entry.variants) {
      if (variant && variant.unicode) add(variant.unicode);
    }
  }
  return labels;
}

function main() {
  const ownedDomains = JSON.parse(fs.readFileSync(OWNED_DOMAINS_PATH, 'utf8'));
  const { LEXICON } = require(LEXICON_PATH);

  const ownedIds = new Set();

  // Pass 1 (authoritative): the archetype list binds owned domains to entry
  // ids directly (primary + alt sets). Alternate restorations that no label
  // match can reach (aphrodītē.com vs Aphrodítē, the cuneiform 𒀭𒂍.com,
  // glottal-letter variants like aṯiratu.com) are attributed here.
  const archetypesPath = path.join(ROOT, 'js', 'archetypes-v2.js');
  const archetypeSrc = fs
    .readFileSync(archetypesPath, 'utf8')
    .replace('const ARCHETYPES', 'var ARCHETYPES');
  const ARCHETYPES = new Function(`${archetypeSrc}; return ARCHETYPES;`)();
  const ownedSet = new Set(
    ownedDomains.map((d) => normalizeLabel(domainToUnicode(d)))
  );
  for (const archetype of ARCHETYPES) {
    const domains = [archetype.domainUnicode, ...(archetype.domainAlt || [])].filter(Boolean);
    if (domains.some((d) => ownedSet.has(normalizeLabel(d)))) {
      ownedIds.add(archetype.id);
    }
  }

  // Pass 2 (label matching): owned domains for entries without an archetype
  // (owned but not yet promoted to flagship).
  const ownedLabels = ownedDomainLabels(ownedDomains);
  for (const entry of LEXICON) {
    if (ownedIds.has(entry.id)) continue;
    const labels = entryLabels(entry);
    for (const label of labels) {
      if (ownedLabels.has(label)) {
        ownedIds.add(entry.id);
        break;
      }
    }
  }

  const ids = Array.from(ownedIds).sort();
  const output = `// PuniCodex — Generated owned-entry lookup
// Source: platform/db/owned-domains.json
// This file is regenerated by scripts/generate-owned-entries.js
const OWNED_ENTRY_IDS = new Set(${JSON.stringify(ids)});
`;

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  writeFileWithRetry(OUTPUT_PATH, output);

  console.log(`✓ Generated ${OUTPUT_PATH}`);
  console.log(`  Owned entries: ${ids.length}`);
}

// Transient Windows file locks (AV/indexer) on freshly written files clear
// within a moment — retry with a short busy-wait before giving up.
function writeFileWithRetry(targetPath, data, attempts = 8, delayMs = 200) {
  let lastErr;
  for (let i = 0; i < attempts; i++) {
    try {
      fs.writeFileSync(targetPath, data, 'utf8');
      return;
    } catch (err) {
      lastErr = err;
      if (!['EPERM', 'EBUSY', 'UNKNOWN'].includes(err.code) || i === attempts - 1) throw err;
      const start = Date.now();
      while (Date.now() - start < delayMs * (i + 1)) {}
    }
  }
  throw lastErr;
}

main();
