/**
 * Build a browser-compatible original-script lookup for the Pantheon page.
 *
 * The Node-only original-scripts.js resolves original scripts from the lexicon
 * and a curated override map. This script precomputes a lightweight
 * id → { originalScript, scriptName } map so the browser can render the
 * correct script under each pantheon card without loading the full lexicon.
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const { getOriginalScript, getScriptName, hasOriginalScript, getOriginalScriptLabel } = require('../type/js/original-scripts.js');

// Load canonical lexicon
const lexiconPath = path.join(__dirname, '..', 'type', 'js', 'lexicon.js');
const lexiconRaw = fs.readFileSync(lexiconPath, 'utf8');
const tmpPath = path.join(__dirname, '_temp_lexicon_osp.js');
fs.writeFileSync(tmpPath, `${lexiconRaw}\nmodule.exports = LEXICON;`);
const LEXICON = require(tmpPath);
fs.unlinkSync(tmpPath);

const lookup = {};
for (const entry of LEXICON) {
  if (!hasOriginalScript(entry)) continue;
  const originalScript = getOriginalScript(entry);
  if (!originalScript || originalScript === '—') continue;
  lookup[entry.id] = {
    originalScript,
    scriptName: getScriptName(entry),
    // "Original Script" vs "Scholarly Transliteration" — the type tool's
    // all-forms chooser must never mislabel a transliteration as the script.
    scriptLabel: getOriginalScriptLabel(entry),
  };
}

const outPath = path.join(__dirname, '..', 'js', 'original-script-lookup.js');
const fileBody = `/**
 * AUTO-GENERATED by scripts/build-original-script-lookup.js
 * Do not edit by hand. Run \`npm run generate\` to refresh.
 */
const ORIGINAL_SCRIPT_LOOKUP = ${JSON.stringify(lookup, null, 2)};

if (typeof window !== 'undefined') {
  window.ORIGINAL_SCRIPT_LOOKUP = ORIGINAL_SCRIPT_LOOKUP;
}
if (typeof module !== 'undefined' && module.exports) {
  module.exports = ORIGINAL_SCRIPT_LOOKUP;
}
`;

fs.writeFileSync(outPath, fileBody);
console.log(`Built original-script lookup: ${Object.keys(lookup).length} entries → ${outPath}`);
