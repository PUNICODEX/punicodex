for (const group of INDUSTRY_GROUPS) {
  if (!group.industry || !group.name || !group.sector || !group.note) {
    throw new Error(`Industry group missing required fields: ${JSON.stringify(group.industry)}`);
  }
  if (!INDUSTRY_SECTORS.some((s) => s.id === group.sector)) {
    throw new Error(`Industry "${group.industry}" references unknown sector "${group.sector}"`);
  }
  if (!Array.isArray(group.entries) || group.entries.length === 0) {
    throw new Error(`Industry "${group.industry}" has no entries`);
  }
  for (const entry of group.entries) {
    if (!validIds.has(entry.id)) {
      throw new Error(`Industry "${group.industry}" references unknown lexicon id "${entry.id}"`);
    }
    if (entry.weight !== 1 && entry.weight !== 2) {
      throw new Error(`Industry "${group.industry}" entry "${entry.id}" has invalid weight ${entry.weight}`);
    }
  }
}

